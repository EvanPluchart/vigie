def po_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    import os
    import subprocess
    import json
    ids = json.loads(subprocess.run(
        ["python", "xtask/tr_extract.py"], capture_output=True, check=True,
        env={**os.environ, "PYTHONIOENCODING": "utf-8"}).stdout.decode("utf-8"))
    missing = [i for i in ids if i not in FR]
    if missing:
        raise SystemExit("no French for:\n" + "\n".join(missing))
    lines = [
        'msgid ""',
        'msgstr ""',
        '"Content-Type: text/plain; charset=UTF-8\\n"',
        '"Language: fr\\n"',
        '"Plural-Forms: nplurals=2; plural=(n > 1);\\n"',
        "",
    ]
    for msgid in ids:
        lines += [f"msgid {po_string(msgid)}", f"msgstr {po_string(FR[msgid])}", ""]
    out = "crates/vigie-app/translations/fr/LC_MESSAGES/vigie.po"
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{len(ids)} strings written to {out}")


if __name__ == "__main__":
    main()
